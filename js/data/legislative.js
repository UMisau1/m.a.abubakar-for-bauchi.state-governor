const legislativeStats = {

    totalLaws: legislativeLaws.length,

    years: [...new Set(
        legislativeLaws.map(law => law.year)
    )],

    categories: [...new Set(
        legislativeLaws.map(law => law.category)
    )],

    recordedLaws: legislativeLaws.filter(
        law => law.status === "Recorded"
    ).length

};


/* =========================================================
   YEAR STATISTICS
========================================================= */

function getLawsByYear(year) {

    return legislativeLaws.filter(
        law => Number(law.year) === Number(year)
    );

}


/* =========================================================
   CATEGORY STATISTICS
========================================================= */

function getLawsByCategory(category) {

    return legislativeLaws.filter(
        law =>
            law.category.toLowerCase() ===
            category.toLowerCase()
    );

}


/* =========================================================
   SEARCH LAWS
========================================================= */

function searchLegislativeLaws(keyword) {

    const searchTerm = String(keyword || "")
        .trim()
        .toLowerCase();

    if (!searchTerm) {
        return legislativeLaws;
    }

    return legislativeLaws.filter(law =>

        String(law.lawNo)
            .toLowerCase()
            .includes(searchTerm)

        ||

        String(law.year)
            .toLowerCase()
            .includes(searchTerm)

        ||

        law.category
            .toLowerCase()
            .includes(searchTerm)

        ||

        law.title
            .toLowerCase()
            .includes(searchTerm)

    );

}


